const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm'), assert = require('node:assert/strict');
const context = vm.createContext({ window: {}, console });
for (const name of ['dimensions', 'regulatory-sign-data', 'street-signs', 'signal-model', 'signal-renderer']) vm.runInContext(fs.readFileSync(path.join(__dirname, '..', 'js', `${name}.js`), 'utf8'), context);
const app = context.window.SignalMaker;
const sign = app.createStreetSign();
sign.icon = { src: 'data:image/png;base64,iVBORw0KGgo=', width: 400, height: 200, name: 'Icon' };
let geometry = app.streetSignGeometry(sign);
assert.equal(geometry.icon.background, undefined);
assert.equal(geometry.icon.width / geometry.icon.height, 2);
sign.iconSquare = true; sign.iconBackground = 'Blue'; sign.iconCorners = 'Round';
geometry = app.streetSignGeometry(sign);
assert.equal(geometry.icon.width, geometry.icon.height);
assert.equal(geometry.icon.background.color, '#00437b');
assert.ok(geometry.icon.background.radius > 0);
let svg = app.streetSignMarkup(sign, geometry);
assert.ok(svg.includes('streetIconBackground'));
assert.ok(svg.includes('street-icon-image-'));
assert.ok(svg.includes('preserveAspectRatio="xMidYMid meet"'));
sign.corner = 'Round'; sign.borderRadius = 1; sign.iconExtendBackground = true;
for (const side of ['left', 'right']) {
  sign.iconSide = side;
  geometry = app.streetSignGeometry(sign);
  const block = geometry.icon.background;
  assert.equal(block.width, geometry.height);
  assert.equal(block.height, geometry.height);
  assert.equal(block.y, 0);
  assert.equal(block.radius, 0);
  assert.equal(block.color, '#ffffff');
  assert.equal(side === 'left' ? block.x : block.x + block.width, side === 'left' ? 0 : geometry.width);
  assert.ok(side === 'left' ? geometry.textX >= block.width : geometry.textX + geometry.textWidth <= block.x);
  assert.ok(app.streetSignMarkup(sign, geometry).includes('street-icon-panel-'));
}
const project = { version: 1, heads: [], streetSigns: [sign] };
const restored = app.restoreProject(JSON.stringify(project)).streetSigns[0];
for (const key of ['iconBackground', 'iconCorners', 'iconSquare', 'iconExtendBackground', 'iconSide']) assert.equal(restored[key], sign[key]);
restored.iconExtendBackground = false;
geometry = app.streetSignGeometry(restored);
assert.equal(geometry.icon.background.color, '#00437b');
assert.ok(geometry.icon.background.radius > 0);
assert.equal(geometry.icon.width, geometry.icon.height);
assert.ok(!app.renderSVG(project).includes('NaN'));
console.log('Icon aspect/corners, background colors, flush white edges, text clearance, restoration and export passed');
restored.iconBackgroundPadding = 2;
const padded = app.streetSignGeometry(restored);
assert.equal(padded.icon.background.width - padded.icon.width, 4);
assert.equal(padded.icon.background.height - padded.icon.height, 4);
assert.equal(padded.icon.x - padded.icon.background.x, 2);
assert.equal(padded.icon.y - padded.icon.background.y, 2);
assert.ok(padded.icon.background.x >= 0);
assert.ok(padded.icon.background.y >= 0);
restored.iconExtendBackground = true;
const flushPadded = app.streetSignGeometry(restored);
restored.iconBackgroundPadding = 0;
const flushPlain = app.streetSignGeometry(restored);
assert.equal(flushPadded.width, flushPlain.width);
assert.equal(flushPadded.height, flushPlain.height);
assert.equal(flushPlain.icon.width - flushPadded.icon.width, 4);
restored.iconBackgroundPadding = 2;
const paddedSaved = app.restoreProject(JSON.stringify({ version: 1, heads: [], streetSigns: [restored] }));
assert.equal(paddedSaved.streetSigns[0].iconBackgroundPadding, 2);
assert.ok(!app.renderSVG(paddedSaved).includes('NaN'));
console.log('Padding reserves background space, preserves flush edges, insets artwork and saves locally');
restored.iconExtendBackground = false;
restored.iconBackgroundPadding = 0;
restored.iconSize = 100;
const baseSize = app.streetSignGeometry(restored);
restored.iconSize = 200;
const largeSize = app.streetSignGeometry(restored);
assert.equal(largeSize.icon.width, baseSize.icon.width * 2);
assert.equal(largeSize.icon.height, baseSize.icon.height * 2);
assert.ok(largeSize.icon.y >= 0);
assert.ok(largeSize.icon.y + largeSize.icon.height <= largeSize.height);
restored.iconExtendBackground = true;
const largeFlush = app.streetSignGeometry(restored);
assert.equal(largeFlush.icon.background.height, largeFlush.height);
assert.ok(largeFlush.icon.width <= largeFlush.icon.background.width);
const row = restored.texts[0];
row.arrow = 'TYPE_A'; row.arrowSize = 100;
const arrowBase = app.streetSignGeometry(restored).rows[0].arrow;
row.arrowSize = 200;
const arrowLarge = app.streetSignGeometry(restored).rows[0].arrow;
assert.equal(arrowLarge.length, arrowBase.length * 2);
assert.equal(arrowLarge.thickness, arrowBase.thickness * 2);
assert.ok(app.streetSignMarkup(restored, app.streetSignGeometry(restored)).includes('streetTextArrow'));
row.arrow = 'TYPE_A_EXTENDED';
const old = app.restoreProject(JSON.stringify({ version: 1, heads: [], streetSigns: [restored] })).streetSigns[0];
assert.equal(old.texts[0].arrow, 'TYPE_A');
assert.equal(old.texts[0].arrowSize, 200);
assert.equal(old.iconSize, 200);
console.log('Icon and arrow sizing fits scene bounds; saved sizes and old Type A Extended migration passed');
