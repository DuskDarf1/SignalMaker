const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const context = vm.createContext({ window: {}, console });
for (const name of ['dimensions', 'regulatory-sign-data', 'street-signs', 'signal-model', 'signal-renderer']) {
  vm.runInContext(fs.readFileSync(path.join(__dirname, '..', 'js', `${name}.js`), 'utf8'), context);
}
const app = context.window.SignalMaker;
const sign = app.createStreetSign();
const row = sign.texts[0];
row.textContent = 'Main';
const plain = app.streetSignGeometry(sign);
const sup = app.createStreetScript(row, 'superscript');
const sub = app.createStreetScript(row, 'subscript');
sup.textContent = 'ST';
sub.textContent = '100 <200>';
sub.fontFamily = 'Series C';
sub.textColor = 'Yellow';
row.scriptElements.push(sup, sub);
row.selectedElementIndex = 2;
assert.equal(app.selectedStreetText(row), sub);
const geometry = app.streetSignGeometry(sign);
assert.equal(geometry.rows.length, 1);
assert.equal(geometry.rows[0].lines.length, 1);
assert.ok(geometry.width > plain.width);
assert.ok(geometry.rows[0].lines[0].find(run => run.element === sup).dy < 0);
assert.ok(geometry.rows[0].lines[0].find(run => run.element === sub).dy > 0);
const svg = app.streetSignMarkup(sign, geometry);
assert.ok(svg.includes('data-script="superscript"'));
assert.ok(svg.includes('data-script="subscript"'));
assert.ok(svg.includes('&lt;'));
assert.ok(svg.includes('#fccf34'));
assert.ok(!svg.includes('NaN'));
const saved = { version: 1, heads: [], streetSigns: [sign], selectedStreetSignId: sign.id };
const restored = app.restoreProject(JSON.stringify(saved));
const copy = restored.streetSigns[0].texts[0];
assert.equal(copy.scriptElements.length, 2);
assert.equal(copy.selectedElementIndex, 2);
assert.equal(copy.scriptElements[1].textContent, sub.textContent);
assert.equal(copy.scriptElements[1].fontFamily, 'Series C');
assert.equal(copy.scriptElements[1].fontSize, 120);
assert.notEqual(copy.scriptElements[1].id, sub.id);
assert.ok(app.renderSVG(restored).includes('data-script="subscript"'));
// Old projects restore an ordinary row without requiring script metadata.
delete row.scriptElements;
delete row.selectedElementIndex;
assert.equal(app.restoreProject(JSON.stringify(saved)).streetSigns[0].texts[0].scriptElements.length, 0);
app.streetFontData = { 'Series EM': 'data:font/woff2;base64,AA==', 'Series C': 'data:font/woff2;base64,AQ==' };
app.embedStreetSignFonts(app.renderSVG(restored), restored).then(embedded => {
  assert.ok(embedded.includes('font-family:"Series C"'));
  assert.ok(embedded.includes('font-family:"Series EM"'));
  console.log('Same-row scripts, baseline offsets, sizing, escaping, color, restoration and PNG font embedding passed');
}).catch(error => { console.error(error); process.exitCode = 1; });
const positioned = app.createStreetSign();
const main = positioned.texts[0];
main.textContent = 'Main';
const left = app.createStreetScript(main, 'superscript');
const right = app.createStreetScript(main, 'subscript');
assert.equal(left.textContent, 'Bch');
assert.equal(right.textContent, 'Bch');
assert.equal(left.scriptSide, 'right');
left.scriptSide = 'left';
main.scriptElements.push(left, right);
const runs = app.streetSignGeometry(positioned).rows[0].lines[0];
const mainIndex = runs.findIndex(run => run.content === 'Main');
assert.ok(runs.findIndex(run => run.element === left) < mainIndex);
assert.ok(runs.findIndex(run => run.element === right) > mainIndex);
const scene = { version: 1, heads: [], streetSigns: [positioned] };
const restoredPositioned = app.restoreProject(JSON.stringify(scene));
assert.equal(restoredPositioned.streetSigns[0].texts[0].scriptElements[0].scriptSide, 'left');
assert.equal(restoredPositioned.streetSigns[0].texts[0].scriptElements[1].scriptSide, 'right');
delete left.scriptSide;
assert.equal(app.restoreProject(JSON.stringify(scene)).streetSigns[0].texts[0].scriptElements[0].scriptSide, 'right');
console.log('Bch defaults, left/right same-row placement and backward-compatible position restoration passed');
